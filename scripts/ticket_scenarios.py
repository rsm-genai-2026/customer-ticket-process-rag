def browser_example_tickets() -> list[dict]:
    """Return a browser-safe deep copy of the scenario catalog.

    The UI mutates form fields, so callers should not receive references
    to the module-level constants.
    """

    return deepcopy(EXAMPLE_TICKETS)


def scenario_by_id(scenario_id: str) -> dict:
    """Return one scenario by id or raise ``KeyError``."""

    for scenario in EXAMPLE_TICKETS:
        if scenario["id"] == scenario_id:
            return deepcopy(scenario)
    raise KeyError(f"unknown scenario id: {scenario_id}")
